"""Prepare personal art photos for the Art background.

Resizes every JPEG in a source folder to the 1920 x 1080 stage with macOS
sips, writes app/assets/art/NN.jpg and app/assets/art/catalog.js, and keeps
the id-to-filename map privately in .local/art-sources.json. Photos are
personal and ignored by Git; only the script and the catalogue are tracked.
"""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'app/assets/art'
parser = argparse.ArgumentParser()
parser.add_argument('source')
parser.add_argument('--quality', type=int, default=88)
args = parser.parse_args()
source = Path(args.source).expanduser()
files = sorted(p for p in source.iterdir() if p.suffix.lower() in {'.jpg', '.jpeg'} and not p.name.startswith('.'))
if not files:
    raise SystemExit('No JPEG files in ' + str(source))
OUT.mkdir(parents=True, exist_ok=True)
for old in OUT.glob('*.jpg'):
    old.unlink()
entries, sources = [], {}
for i, path in enumerate(files, 1):
    art_id = '%02d' % i
    target = OUT / (art_id + '.jpg')
    subprocess.run(['sips', '-z', '1080', '1920', '-s', 'format', 'jpeg', '-s', 'formatOptions', str(args.quality),
                    str(path), '--out', str(target)], check=True, capture_output=True)
    entries.append({'id': art_id, 'src': 'assets/art/' + art_id + '.jpg'})
    sources[art_id] = path.name
(OUT / 'catalog.js').write_text('/* Personal art photos for the Art background. Generated by scripts/prepare-art.py. */\n'
                                'window.CleanFrameArt = ' + json.dumps(entries, indent=2) + ';\n')
(ROOT / '.local').mkdir(exist_ok=True)
(ROOT / '.local/art-sources.json').write_text(json.dumps(sources, indent=2) + '\n')
total = sum(p.stat().st_size for p in OUT.glob('*.jpg'))
print('Prepared %d photos (%.1f MB) in %s' % (len(entries), total / 1e6, OUT))
